#!/usr/bin/env node
// Generates public/sitemap-zh.xml — every /zh URL with xhtml:link alternates
// (en, de, de-AT, de-CH, zh-Hans, zh-CN, x-default). Runs before `next build` (prebuild)
// so the file always matches the routes and data being deployed.
//
// Slugs are read straight from the data files (services from lib/site.ts,
// posts from data/blog.ts + data/blog.zh/index.ts, case studies from
// data/portfolio.ts) with simple pattern matching, so this stays a plain
// Node script with no TypeScript toolchain.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const BASE = "https://globalannotate.com";
const TODAY = new Date().toISOString().slice(0, 10);
const SITE_LAST_UPDATED = "2026-10-22";

const slugsIn = (src) => [...src.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]);
const between = (src, start, end) => {
  const i = src.indexOf(start);
  if (i === -1) throw new Error(`marker not found: ${start}`);
  const j = end ? src.indexOf(end, i) : src.length;
  return src.slice(i, j === -1 ? src.length : j);
};

// Services (the five in `services`) + MarketReady.
const siteSrc = read("lib/site.ts");
const serviceSlugs = [
  ...slugsIn(between(siteSrc, "export const services", "] as const;")),
  "marketready",
];

// Blog: English posts (translated on /zh) + zh-only posts.
const blogSrc = read("data/blog.ts");
const postEntries = [
  ...between(blogSrc, "export const posts", "export function getPost").matchAll(
    /slug:\s*"([^"]+)",[\s\S]*?date:\s*"([^"]+)"/g
  ),
].map((m) => ({ slug: m[1], date: m[2], zhOnly: false }));
const zhIndexSrc = read("data/blog.zh/index.ts");
const zhOnlyEntries = [
  ...between(zhIndexSrc, "export const zhOnlyPosts").matchAll(
    /zhOnly\(\s*"([^"]+)",\s*"([^"]+)"/g
  ),
].map((m) => ({ slug: m[1], date: m[2], zhOnly: true }));

// Case studies.
const portfolioSrc = read("data/portfolio.ts");
const caseEntries = [
  ...between(portfolioSrc, "export const cases", "export function getCase").matchAll(
    /slug:\s*"([^"]+)",[\s\S]*?lastUpdated:\s*"([^"]+)"/g
  ),
].map((m) => ({ slug: m[1], date: m[2] }));

const staticPaths = [
  ["", "1.0", "weekly"],
  ["/services", "0.9", "monthly"],
  ["/languages", "0.9", "monthly"],
  ["/translation-services-nigeria", "0.9", "monthly"],
  ["/translation-services-africa", "0.9", "monthly"],
  ["/industries", "0.85", "monthly"],
  ["/portfolio", "0.85", "monthly"],
  ["/procurement", "0.7", "monthly"],
  ["/quality", "0.7", "monthly"],
  ["/security", "0.7", "monthly"],
  ["/reviews", "0.7", "monthly"],
  ["/about", "0.7", "monthly"],
  ["/freelancers", "0.6", "monthly"],
  ["/contact", "0.7", "monthly"],
  ["/blog", "0.8", "weekly"],
  ["/privacy", "0.3", "yearly"],
  ["/terms", "0.3", "yearly"],
];

const entries = [
  ...staticPaths.map(([path, priority, freq]) => ({ path, priority, freq, date: SITE_LAST_UPDATED })),
  ...serviceSlugs.map((s) => ({ path: `/services/${s}`, priority: "0.9", freq: "monthly", date: SITE_LAST_UPDATED })),
  ...[...zhOnlyEntries, ...postEntries].map((p) => ({
    path: `/blog/${p.slug}`,
    priority: p.zhOnly ? "0.85" : "0.75",
    freq: "monthly",
    date: p.date,
    zhOnly: p.zhOnly,
  })),
  ...caseEntries.map((c) => ({ path: `/portfolio/${c.slug}`, priority: "0.8", freq: "monthly", date: c.date })),
];

const url = (locale, path) => (locale === "en" ? `${BASE}${path}` : `${BASE}/${locale}${path}`);
const esc = (s) => s.replace(/&/g, "&amp;");

const body = entries
  .map((e) => {
    const zh = url("zh", e.path);
    const alts = e.zhOnly
      ? [["zh-Hans", zh], ["zh-CN", zh]]
      : [
          ["en", url("en", e.path)],
          ["de", url("de", e.path)],
          ["de-AT", url("de", e.path)],
          ["de-CH", url("de", e.path)],
          ["zh-Hans", zh],
          ["zh-CN", zh],
          ["x-default", url("en", e.path)],
        ];
    return [
      "  <url>",
      `    <loc>${esc(zh)}</loc>`,
      ...alts.map(
        ([lang, href]) => `    <xhtml:link rel="alternate" hreflang="${lang}" href="${esc(href)}" />`
      ),
      `    <lastmod>${e.date}</lastmod>`,
      `    <changefreq>${e.freq}</changefreq>`,
      `    <priority>${e.priority}</priority>`,
      "  </url>",
    ].join("\n");
  })
  .join("\n");

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap-zh.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${body}
</urlset>
`;

writeFileSync(join(root, "public/sitemap-zh.xml"), xml);
console.log(`[sitemap-zh] wrote ${entries.length} /zh URLs to public/sitemap-zh.xml (${TODAY})`);
