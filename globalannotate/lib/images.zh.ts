export function zhAlt(id: string, fallback = "GlobalAnnotate 配图"): string {
  return ZH_ALT[id] ?? fallback;
}

export function zhImage<T extends ImageRef>(ref: T): T {
  return { ...ref, alt: zhAlt(ref.id) };
}

export function zhSlides(slides: ImageRef[]): ImageRef[] {
  return slides.map(zhImage);
}
